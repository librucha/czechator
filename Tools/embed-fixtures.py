#!/usr/bin/env python3
"""Embeds the fixture sets into a Swift source file.

The fixtures are the source of truth; this file only mirrors them so the CLI
can measure without a repository checkout. `make fixtures` regenerates it and a
test fails if the mirror drifts.

Written rather than hand-maintained because one sample is CRLF and two carry
JSON escapes — transcribing those into Swift literals by hand is a mistake you
only notice as a wrong number in a table.
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "Sources" / "CzechatorCore" / "Quality" / "QualityFixtures+Embedded.swift"
SETS = (("clean", "quality"), ("typos", "typos"))


def literal(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + out.replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t") + '"'


def samples(directory: pathlib.Path) -> list[str]:
    rows = []
    for source in sorted(directory.glob("*.in")):
        reference = source.with_suffix(".want")
        if not reference.exists():
            raise SystemExit(f"chybí reference pro {source.name}")
        # newline="" keeps CRLF as CRLF instead of translating it to LF.
        with open(source, encoding="utf-8", newline="") as handle:
            text_in = handle.read()
        with open(reference, encoding="utf-8", newline="") as handle:
            text_want = handle.read()
        rows.append(
            f'        QualitySample(\n'
            f'            name: "{source.stem}",\n'
            f'            input: {literal(text_in)},\n'
            f'            want: {literal(text_want)}),'
        )
    return rows


def main() -> int:
    blocks = []
    for name, directory in SETS:
        rows = "\n".join(samples(ROOT / "Fixtures" / directory))
        blocks.append(
            f"    public static let {name} = QualityFixtureSet(\n"
            f'        name: "{name}",\n'
            f"        samples: [\n{rows}\n        ])"
        )
    OUT.write_text(
        "// Generated by Tools/embed-fixtures.py — do not edit by hand.\n"
        "// Source of truth: Fixtures/quality/ and Fixtures/typos/\n"
        "// Regenerate with `make fixtures`.\n\n"
        "extension QualityFixtures {\n\n" + "\n\n".join(blocks) + "\n}\n",
        encoding="utf-8",
    )
    print(f"zapsáno {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
